#!/usr/bin/env python3
"""Write or check the Claude Code project-skill entries for the Blitz methods.

tools/claude_skills.json names the methods to expose. Each
.claude/skills/<name>/SKILL.md repeats its method's frontmatter bytes and
points to Blitz/skills/<name>/, which stays the only copy of the method.
The check fails on a missing, extra, changed or non-regular entry. It never
deletes files and never reads outside this repository.
"""
import argparse
import importlib.util
import json
from pathlib import Path
import re
import stat
import sys

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
SOURCE = "Blitz/skills"
TARGET = ".claude/skills"
SELECTION = "tools/claude_skills.json"
BODY = """
<!-- Generated by tools/sync_claude_skills.py from Blitz/skills/{name}/SKILL.md. Do not edit. -->

# {name}

This project skill exposes the Blitz method `{name}`. The method is in this repository at `Blitz/skills/{name}/`. From the folder of this file, that is `../../../Blitz/skills/{name}/`.

1. Read `Blitz/skills/{name}/SKILL.md` in full. Follow it as the instructions for this skill.
2. Resolve each relative path in that file, such as references, scripts and assets, from `Blitz/skills/{name}/`.
3. When you report the work, name the method file that you read. If you cannot read it, say so and stop. This entry is a pointer, not the method.
"""


def frontmatter_parser(root):
    spec = importlib.util.spec_from_file_location("blitz_frontmatter", root / "Blitz/setup/frontmatter.py")
    loaded = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(loaded)
    return loaded.parse_skill_frontmatter


def regular(path):
    try:
        return stat.S_ISREG(path.lstat().st_mode)
    except OSError:
        return False


def selected_methods(root, names):
    selection = json.loads((root / SELECTION).read_text(encoding="utf-8"))
    exposed = selection.get("expose") if isinstance(selection, dict) and set(selection) == {"expose"} else None
    if not isinstance(exposed, list) or not exposed or exposed != sorted(set(exposed)):
        raise ValueError(SELECTION + " needs one sorted, unique, nonempty expose list")
    unknown = [name for name in exposed if name not in names]
    if unknown:
        raise ValueError(SELECTION + " names unknown methods: " + ", ".join(map(str, unknown)))
    return exposed


def expected_entries(root):
    """Return {relative path: bytes} for every entry the selection requires."""
    root = Path(root).resolve()
    parse = frontmatter_parser(root)
    manifest = json.loads((root / "Blitz/manifest.json").read_text(encoding="utf-8"))
    names = sorted(row["name"] for row in manifest["skills"])
    found = sorted(path.parent.name for path in (root / SOURCE).glob("*/SKILL.md"))
    if names != found:
        raise ValueError("Blitz/skills differs from the manifest method list")
    entries = {}
    for name in selected_methods(root, names):
        source = root / SOURCE / name / "SKILL.md"
        if not regular(source):
            raise ValueError("non-regular method file: " + name)
        text = source.read_bytes().decode("utf-8")
        head = re.match(r"^---\n.*?\n---\n", text, re.S)
        if not head or parse(text)["name"] != name:
            raise ValueError("method frontmatter does not name its folder: " + name)
        entries[TARGET + "/" + name + "/SKILL.md"] = (head.group(0) + BODY.format(name=name)).encode("utf-8")
    return entries


def check(root=ROOT):
    root = Path(root).resolve()
    expected = expected_entries(root)
    target = root / TARGET
    actual = set()
    findings = []
    if target.is_symlink() or (target.exists() and not target.is_dir()):
        findings.append({"path": TARGET, "rule": "non-directory-target"})
    elif target.exists():
        for path in sorted(target.rglob("*")):
            rel = path.relative_to(root).as_posix()
            if path.is_symlink():
                findings.append({"path": rel, "rule": "symlink"})
            elif path.is_file():
                actual.add(rel)
    for rel in sorted(actual - set(expected)):
        findings.append({"path": rel, "rule": "unexpected-entry"})
    for rel, data in sorted(expected.items()):
        path = root / rel
        if rel not in actual:
            findings.append({"path": rel, "rule": "missing-entry"})
        elif not regular(path) or path.read_bytes() != data:
            findings.append({"path": rel, "rule": "changed-entry"})
    return {"result": "fail" if findings else "pass", "exposed": len(expected), "findings": findings,
            "limits": "Checks entry bytes against the selected methods only. It does not prove that a host lists, selects or runs a skill."}


def write(root=ROOT):
    root = Path(root).resolve()
    for rel, data in expected_entries(root).items():
        path = root / rel
        if path.is_symlink() or (path.exists() and not path.is_file()):
            raise ValueError("refusing to replace a non-regular entry: " + rel)
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
    return check(root)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["check", "write"])
    parser.add_argument("--repo", type=Path, default=ROOT)
    args = parser.parse_args()
    try:
        report = check(args.repo) if args.command == "check" else write(args.repo)
    except (OSError, ValueError, KeyError, TypeError, UnicodeDecodeError) as error:
        report = {"result": "fail", "error": str(error)}
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0 if report["result"] == "pass" else 1


if __name__ == "__main__":
    raise SystemExit(main())
